export const LANGS = ['ko', 'en'];

export function detectLang() {
  const loc = process.env.LC_ALL || process.env.LANG || Intl.DateTimeFormat().resolvedOptions().locale || 'ko';
  return /^en/i.test(String(loc)) ? 'en' : 'ko';
}

